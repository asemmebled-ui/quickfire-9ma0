/** Spec coverage report: every 9MA0 content point and how many bank entries cover it. Fails on any gap. */
import { writeFileSync } from 'node:fs'
import { BANK } from '../src/content/index'
import { SPEC_POINTS, TOPICS } from '../src/content/topics'

const count: Record<string, { items: number; gens: number; cards: number }> = Object.fromEntries(SPEC_POINTS.map((p) => [p, { items: 0, gens: 0, cards: 0 }]))
const unknown = new Set<string>()
for (const e of BANK) for (const p of e.spec) {
  const c = count[p]
  if (!c) { unknown.add(`${p} (${e.id})`); continue }
  if (e.isGen) c.gens++; else if (e.type === 'card') c.cards++; else c.items++
}
const gaps = SPEC_POINTS.filter((p) => count[p].items + count[p].gens === 0)
const lines = ['| Spec point | Questions | Generators | Flashcards |', '|---|---|---|---|', ...SPEC_POINTS.map((p) => `| ${p} | ${count[p].items} | ${count[p].gens} | ${count[p].cards} |`)]
const nGen = BANK.filter((e) => e.isGen).length, nCard = BANK.filter((e) => e.type === 'card').length, nItem = BANK.length - nGen - nCard
const summary = `Bank: ${nItem} hand-written questions, ${nGen} parameterised generators (unlimited variants), ${nCard} flashcards. ${BANK.length} schedulable cards in ${TOPICS.length} topics.`
writeFileSync('COVERAGE.md', `# Spec coverage report\n\n${summary}\n\nGenerated by \`npm run check:coverage\`. "Questions" and "Generators" count quiz items; flashcards are extra.\n\n${lines.join('\n')}\n`)
console.log(summary)
const minP = SPEC_POINTS.reduce((m, p) => Math.min(m, count[p].items + count[p].gens), Infinity)
console.log(`${SPEC_POINTS.length} spec points; minimum quiz entries on any point: ${minP}. Report written to COVERAGE.md.`)
if (unknown.size) { console.error('Unknown spec references: ' + [...unknown].join(', ')); process.exit(1) }
if (gaps.length) { console.error(`GAPS (${gaps.length}): ${gaps.join(', ')}`); process.exit(1) }
console.log('ZERO GAPS: every spec point has at least one quiz item or generator.')
